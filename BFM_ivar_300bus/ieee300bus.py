# ieee300bus.py
# ------------------------------------------------------------
# IEEE 300-bus system builder for OPF / PF in pandapower
#
# Design philosophy
# -----------------
# 1) Preserve the uploaded MATPOWER case300 bus / gen / branch / gencost data.
# 2) Use quadratic generator cost functions directly from MATPOWER.
# 3) Keep the original active / reactive loads from MATPOWER bus data.
# 4) Add OPF-friendly synthetic branch ratings because MATPOWER case300
#    has rateA = rateB = rateC = 0 for all branches.
# 5) Expose OLTC and switched-shunt candidates in a style similar to
#    your ieee118bus.py file, but keep candidate counts comparable to
#    the 118-bus case (11 OLTC, 13 switched shunts).
#
# Notes
# -----
# - Internal pandapower bus indexing is 0..299 in the SAME ORDER as the
#   uploaded MATPOWER bus table.
# - Original MATPOWER bus numbers are NOT contiguous in case300
#   (e.g. 7001, 7049, 9001, 9533 also appear), so explicit lookup maps
#   are provided and preserved in metadata.
# - Same-kV ratio=0 branches are created as pandapower lines.
# - Branches with non-zero tap ratio or different base-kV are created as
#   pandapower transformers with approximate synthetic ratings.
# - Original bus shunts (Gs, Bs) are preserved and can optionally be
#   instantiated as pandapower shunts.
# - OLTC / switched-shunt candidates are metadata only by default.
# ------------------------------------------------------------

