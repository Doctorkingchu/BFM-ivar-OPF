def _create_transformer_from_branch(
    net,
    hv_bus,
    lv_bus,
    hv_kv: float,
    lv_kv: float,
    r_pu: float,
    x_pu: float,
    angle_deg: float,
    sn_sys_mva: float,
    sn_trafo_mva: float,
    name: str,
    tap_min: int,
    tap_max: int,
    tap_step_percent: float,
):
    """
    Approximate a MATPOWER transformer-like branch with a pandapower trafo.

    r_pu, x_pu are given on the system base (sn_sys_mva).
    For pandapower trafo parameters on trafo base sn_trafo_mva:
        z_trafo_pu = z_sys_pu * (sn_trafo_mva / sn_sys_mva)
    """
    z_sys = complex(float(r_pu), float(x_pu))
    z_trafo_pu = z_sys * (float(sn_trafo_mva) / float(sn_sys_mva))
    vk_percent = 100.0 * abs(z_trafo_pu)
    vkr_percent = 100.0 * max(z_trafo_pu.real, 1e-6)

    return pp.create_transformer_from_parameters(
        net,
        hv_bus=hv_bus,
        lv_bus=lv_bus,
        sn_mva=float(sn_trafo_mva),
        vn_hv_kv=float(hv_kv),
        vn_lv_kv=float(lv_kv),
        vk_percent=float(vk_percent),
        vkr_percent=float(vkr_percent),
        pfe_kw=0.0,
        i0_percent=0.0,
        shift_degree=float(angle_deg),
        tap_side="hv",
        tap_neutral=0,
        tap_min=int(tap_min),
        tap_max=int(tap_max),
        tap_step_percent=float(tap_step_percent),
        tap_pos=0,
        name=name,
    )


