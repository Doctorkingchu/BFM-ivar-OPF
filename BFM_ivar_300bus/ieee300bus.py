def _apply_ver11_cost_uplift(net):
    if not hasattr(net, "poly_cost") or net.poly_cost is None or net.poly_cost.empty:
        return net

    df = net.poly_cost.copy()
    if "cp1_eur_per_mw" in df.columns:
        df["cp1_eur_per_mw"] = df["cp1_eur_per_mw"].astype(float) * float(GEN_COST_LINEAR_SCALE)
    if "cp2_eur_per_mw2" in df.columns:
        df["cp2_eur_per_mw2"] = df["cp2_eur_per_mw2"].astype(float) * float(GEN_COST_QUADRATIC_SCALE)
    if "cp0_eur" in df.columns:
        df["cp0_eur"] = df["cp0_eur"].astype(float) * float(GEN_COST_FIXED_SCALE)
    net.poly_cost = df
    net["ver11_cost_uplift"] = {
        "cp0_scale": float(GEN_COST_FIXED_SCALE),
        "cp1_scale": float(GEN_COST_LINEAR_SCALE),
        "cp2_scale": float(GEN_COST_QUADRATIC_SCALE),
    }
    return net


