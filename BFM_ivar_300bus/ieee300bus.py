def case300_opf(
    line_max_loading_percent: float = 100.0,
    trafo_max_loading_percent: float = 100.0,
    line_smax_mva_overrides: Optional[Dict[Tuple[int, int], float]] = None,
    apply_fixed_bus_shunts: bool = True,
    oltc_step_percent: float = 1.25,
    calibrate_branch_limits_from_pf: bool = False,
    pf_branch_headroom: float = 2.00,
    pf_branch_floor_mva: float = 100.0,
    widen_voltage_bounds_from_pf: bool = False,
    pf_voltage_margin_pu: float = 0.02,
):
    """
    Build an OPF-ready pandapower network from the uploaded MATPOWER case300.

    Parameters
    ----------
    line_max_loading_percent : float
        Uniform loading limit (%) for lines.
    trafo_max_loading_percent : float
        Uniform loading limit (%) for transformers.
    line_smax_mva_overrides : dict or None
        Optional branch thermal rating overrides in MVA.
        Keys use original MATPOWER bus numbers, e.g. {(3, 1): 500.0}.
    apply_fixed_bus_shunts : bool
        If True, raw MATPOWER bus shunts (Gs, Bs) are instantiated as pandapower shunts.
        Positive Bs in MATPOWER means reactive injection at V=1.0 pu, so the pandapower
        shunt is created with q_mvar = -Bs to preserve the same sign convention.
    oltc_step_percent : float
        Metadata tap step used for OLTC candidate branches.
    calibrate_branch_limits_from_pf : bool
        If True, run a PF and enlarge synthetic branch ratings so they are at least
        a headroom multiple of the observed PF branch loading.
    pf_branch_headroom : float
        Multiplicative headroom used for PF-based synthetic branch rating calibration.
        The requested value is respected directly; it is not silently clamped upward.
    pf_branch_floor_mva : float
        Minimum per-branch rating used during PF-based calibration.
        The requested value is respected directly; it is not silently clamped upward.
    widen_voltage_bounds_from_pf : bool
        If True, expand bus voltage bounds just enough to contain the PF solution
        with the specified margin.
    pf_voltage_margin_pu : float
        Extra voltage margin used when widening bus limits from PF.
        The requested value is respected directly; it is not silently clamped upward.
    """
    net = pp.create_empty_network(sn_mva=MATPOWER_BASE_MVA, f_hz=50.0)

    # --------------------------------------------------------
    # Buses
    # --------------------------------------------------------
    bus_lookup: Dict[int, int] = {}
    bus_base_kv: Dict[int, float] = {}
    bus_type_map: Dict[int, int] = {}

    for row in BUS_DATA:
        (
            bus_i, btype, Pd, Qd, Gs, Bs, area, Vm, Va,
            baseKV, zone, Vmax, Vmin
        ) = row

        bus_i = int(bus_i)
        # Keep the original MATPOWER voltage box so that reactive stress and
        # local voltage support decisions remain binding in the OPF models.
        pp_idx = pp.create_bus(
            net,
            vn_kv=float(baseKV),
            name=f"Bus {bus_i}",
            min_vm_pu=float(Vmin),
            max_vm_pu=float(Vmax),
        )
        bus_lookup[bus_i] = pp_idx
        bus_base_kv[bus_i] = float(baseKV)
        bus_type_map[bus_i] = int(btype)

    net.bus["mpc_bus_id"] = BUS_ID_ORDER
    net.bus["bus_name_raw"] = [f"Bus {bus_id}" for bus_id in BUS_ID_ORDER]

    # --------------------------------------------------------
    # Slack / ext_grid
    # --------------------------------------------------------
    slack_buses = [int(r[0]) for r in BUS_DATA if int(r[1]) == 3]
    if len(slack_buses) != 1:
        raise ValueError(f"Expected exactly one slack bus, found {slack_buses}")
    slack_mp = slack_buses[0]
    slack_pp = bus_lookup[slack_mp]

    slack_bus_row = next(r for r in BUS_DATA if int(r[0]) == slack_mp)
    slack_gen_row = next(r for r in GEN_DATA if int(r[0]) == slack_mp)
    slack_gencost_row = GENCOST_DATA[GEN_DATA.index(slack_gen_row)]

    _, _, _, _, _, _, _, Vm_slack, Va_slack, _, _, Vmax_slack, Vmin_slack = slack_bus_row
    (
        _, Pg, Qg, Qmax, Qmin, Vg, mBase, status,
        Pmax, Pmin, *_rest
    ) = slack_gen_row
    _, startup, shutdown, ncost, c2, c1, c0 = slack_gencost_row

    eg = pp.create_ext_grid(
        net,
        bus=slack_pp,
        vm_pu=float(Vg),
        va_degree=float(Va_slack),
        name=f"Slack@bus{slack_mp}",
    )
    if "controllable" not in net.ext_grid.columns:
        net.ext_grid["controllable"] = True
    net.ext_grid.at[eg, "controllable"] = True
    net.ext_grid.loc[eg, ["min_p_mw", "max_p_mw"]] = [float(Pmin), float(Pmax)]
    qcap_scale = float(AGGRESSIVE_GEN_QCAP_SCALE_MP.get(slack_mp, 1.0))
    net.ext_grid.loc[eg, ["min_q_mvar", "max_q_mvar"]] = [float(Qmin) * qcap_scale, float(Qmax) * qcap_scale]
    net.ext_grid.loc[eg, ["min_vm_pu", "max_vm_pu"]] = [float(Vmin_slack), float(Vmax_slack)]

    pp.create_poly_cost(
        net,
        element=eg,
        et="ext_grid",
        cp2_eur_per_mw2=float(c2),
        cp1_eur_per_mw=float(c1),
        cp0_eur=float(c0),
    )

    # --------------------------------------------------------
    # Generators (all raw MATPOWER generators except slack bus gen)
    # --------------------------------------------------------
    for gen_row, cost_row in zip(GEN_DATA, GENCOST_DATA):
        (
            bus_i, Pg, Qg, Qmax, Qmin, Vg, mBase, status,
            Pmax, Pmin, Pc1, Pc2, Qc1min, Qc1max, Qc2min, Qc2max,
            ramp_agc, ramp_10, ramp_30, ramp_q, apf
        ) = gen_row

        bus_i = int(bus_i)
        if bus_i == slack_mp:
            continue

        g = pp.create_gen(
            net,
            bus=bus_lookup[bus_i],
            p_mw=float(Pg),
            vm_pu=float(Vg),
            name=f"Gen@bus{bus_i}",
            controllable=bool(int(status)),
        )
        net.gen.loc[g, ["min_p_mw", "max_p_mw"]] = [float(Pmin), float(Pmax)]
        qcap_scale = float(AGGRESSIVE_GEN_QCAP_SCALE_MP.get(bus_i, 1.0))
        net.gen.loc[g, ["min_q_mvar", "max_q_mvar"]] = [float(Qmin) * qcap_scale, float(Qmax) * qcap_scale]

        bus_row = next(r for r in BUS_DATA if int(r[0]) == bus_i)
        Vmax = float(bus_row[11])
        Vmin = float(bus_row[12])
        net.gen.loc[g, ["min_vm_pu", "max_vm_pu"]] = [float(Vmin), float(Vmax)]

        _, startup, shutdown, ncost, c2, c1, c0 = cost_row
        pp.create_poly_cost(
            net,
            element=g,
            et="gen",
            cp2_eur_per_mw2=float(c2),
            cp1_eur_per_mw=float(c1),
            cp0_eur=float(c0),
        )

    # --------------------------------------------------------
    # Loads (raw MATPOWER bus Pd / Qd)
    # --------------------------------------------------------
    aggressive_direct_rows = []
    for row in BUS_DATA:
        bus_i, btype, Pd, Qd, Gs, Bs, area, Vm, Va, baseKV, zone, Vmax, Vmin = row
        bus_i = int(bus_i)
        Pd = float(Pd)
        Qd = float(Qd)

        p_scale, q_scale = AGGRESSIVE_DIRECT_LOAD_SCALE.get(bus_i, (1.0, 1.0))
        Pd_mod = Pd * p_scale
        Qd_mod = Qd * q_scale

        if Pd_mod > 1e-12 or Qd_mod > 1e-12:
            pp.create_load(
                net,
                bus=bus_lookup[bus_i],
                p_mw=Pd_mod,
                q_mvar=Qd_mod,
                name=f"Load@bus{bus_i}",
            )

        aggressive_direct_rows.append({
            "bus_mp": bus_i,
            "bus_pp": bus_lookup[bus_i],
            "pd_mw_base": Pd,
            "qd_mvar_base": Qd,
            "p_scale": p_scale,
            "q_scale": q_scale,
            "pd_mw_used": Pd_mod,
            "qd_mvar_used": Qd_mod,
        })

    # --------------------------------------------------------
    # Raw MATPOWER bus shunts (Gs / Bs)
    # --------------------------------------------------------
    fixed_bus_shunt_rows = []
    for row in BUS_DATA:
        bus_i, btype, Pd, Qd, Gs, Bs, area, Vm, Va, baseKV, zone, Vmax, Vmin = row
        bus_i = int(bus_i)
        Gs = float(Gs)
        Bs = float(Bs)

        bs_scale = float(AGGRESSIVE_FIXED_BS_SCALE_MP.get(bus_i, 1.0))
        Bs = Bs * bs_scale
        if abs(Gs) > 1e-12 or abs(Bs) > 1e-12:
            fixed_bus_shunt_rows.append({
                "bus_mp": bus_i,
                "bus_pp": bus_lookup[bus_i],
                "gs_mw_at_v1": Gs,
                "bs_mvar_at_v1": Bs,
                "g_pu": Gs / MATPOWER_BASE_MVA,
                "b_pu": Bs / MATPOWER_BASE_MVA,
            })
            if apply_fixed_bus_shunts:
                pp.create_shunt(
                    net,
                    bus=bus_lookup[bus_i],
                    p_mw=float(Gs),
                    q_mvar=float(-Bs),
                    name=f"FixedBusShunt@bus{bus_i}",
                )

    # --------------------------------------------------------
    # Branches
    # --------------------------------------------------------
    branch_rows = []
    line_counter = 0
    trafo_counter = 0

    for k, br in enumerate(BRANCH_DATA):
        (
            fbus_mp, tbus_mp, r_pu, x_pu, b_pu, rateA, rateB, rateC,
            ratio, angle, status, angmin, angmax
        ) = br

        fbus_mp = int(fbus_mp)
        tbus_mp = int(tbus_mp)
        fbus_pp = bus_lookup[fbus_mp]
        tbus_pp = bus_lookup[tbus_mp]

        from_kv = bus_base_kv[fbus_mp]
        to_kv = bus_base_kv[tbus_mp]

        stress_key = frozenset((fbus_mp, tbus_mp))
        stress_spec = AGGRESSIVE_BRANCH_STRESS.get(stress_key, None)

        r_pu = float(r_pu)
        x_pu = float(x_pu)
        if stress_spec is not None:
            r_pu *= float(stress_spec.get("r_scale", 1.0))
            x_pu *= float(stress_spec.get("x_scale", 1.0))

        is_transformer = _branch_is_transformer_like(from_kv, to_kv, ratio)
        smax_mva = _branch_smax_mva(
            fbus_mp, tbus_mp,
            from_kv=from_kv,
            to_kv=to_kv,
            is_transformer=is_transformer,
            overrides=line_smax_mva_overrides,
        )
        if stress_spec is not None:
            smax_mva = float(smax_mva) * float(stress_spec.get("smax_scale", 1.0))

        if (not is_transformer) and abs(float(ratio)) <= 1e-12:
            line_vn_kv = float(from_kv)
            max_i_ka = _smax_mva_to_imax_ka(smax_mva, line_vn_kv)
            line_idx = _create_line_pu(
                net,
                from_bus=fbus_pp,
                to_bus=tbus_pp,
                r_pu=float(r_pu),
                x_pu=float(x_pu),
                b_pu=float(b_pu),
                sn_mva=MATPOWER_BASE_MVA,
                vn_kv=line_vn_kv,
                max_i_ka=max_i_ka,
                name=f"Line {fbus_mp}-{tbus_mp}",
            )
            net.line.at[line_idx, "max_loading_percent"] = float(line_max_loading_percent)
            element_type = "line"
            element_index = line_idx
            line_counter += 1
        else:
            hv_mp = fbus_mp if from_kv >= to_kv else tbus_mp
            lv_mp = tbus_mp if from_kv >= to_kv else fbus_mp
            hv_pp = bus_lookup[hv_mp]
            lv_pp = bus_lookup[lv_mp]
            hv_kv = bus_base_kv[hv_mp]
            lv_kv = bus_base_kv[lv_mp]

            sorted_edge_pp = tuple(sorted((_mp_to_pp(fbus_mp), _mp_to_pp(tbus_mp))))
            cfg = FIXED_OLTC_CONFIGS_UNDIR.get(sorted_edge_pp, OLTCBranchConfig())
            trafo_idx = _create_transformer_from_branch(
                net,
                hv_bus=hv_pp,
                lv_bus=lv_pp,
                hv_kv=hv_kv,
                lv_kv=lv_kv,
                r_pu=float(r_pu),
                x_pu=float(x_pu),
                angle_deg=float(angle),
                sn_sys_mva=MATPOWER_BASE_MVA,
                sn_trafo_mva=float(smax_mva),
                name=f"Trafo {fbus_mp}-{tbus_mp}",
                tap_min=cfg.tap_min,
                tap_max=cfg.tap_max,
                tap_step_percent=float(oltc_step_percent),
            )
            net.trafo.at[trafo_idx, "max_loading_percent"] = float(trafo_max_loading_percent)
            element_type = "trafo"
            element_index = trafo_idx
            trafo_counter += 1

        branch_rows.append({
            "branch_id": k,
            "from_bus_mp": fbus_mp,
            "to_bus_mp": tbus_mp,
            "from_bus_pp": _mp_to_pp(fbus_mp),
            "to_bus_pp": _mp_to_pp(tbus_mp),
            "r_pu": float(r_pu),
            "x_pu": float(x_pu),
            "aggressive_stress_applied": bool(stress_spec is not None),
            "aggressive_r_scale": 1.0 if stress_spec is None else float(stress_spec.get("r_scale", 1.0)),
            "aggressive_x_scale": 1.0 if stress_spec is None else float(stress_spec.get("x_scale", 1.0)),
            "aggressive_smax_scale": 1.0 if stress_spec is None else float(stress_spec.get("smax_scale", 1.0)),
            "b_pu": float(b_pu),
            "rateA_raw": float(rateA),
            "rateB_raw": float(rateB),
            "rateC_raw": float(rateC),
            "ratio_raw": float(ratio),
            "angle_deg": float(angle),
            "status": int(status),
            "angmin": float(angmin),
            "angmax": float(angmax),
            "from_kv": float(from_kv),
            "to_kv": float(to_kv),
            "is_transformer_like": bool(is_transformer),
            "synthetic_smax_mva": float(smax_mva),
            "element_type": element_type,
            "element_index": int(element_index),
            "is_candidate_oltc": tuple(sorted((_mp_to_pp(fbus_mp), _mp_to_pp(tbus_mp)))) in FIXED_OLTC_CONFIGS_UNDIR,
        })

    # --------------------------------------------------------
    # Extra synthetic lines (disabled for pure MATPOWER case)
    # --------------------------------------------------------
    extra_line_rows = []
    extra_start_id = len(BRANCH_DATA)
    for kk, spec in enumerate(AGGRESSIVE_EXTRA_MESH_LINES):
        fbus_mp = int(spec["from_mp"])
        tbus_mp = int(spec["to_mp"])
        fbus_pp = bus_lookup[fbus_mp]
        tbus_pp = bus_lookup[tbus_mp]
        from_kv = bus_base_kv[fbus_mp]
        to_kv = bus_base_kv[tbus_mp]
        if abs(float(from_kv) - float(to_kv)) > 1e-9:
            continue
        line_vn_kv = float(from_kv)
        smax_mva = float(spec["smax_mva"])
        max_i_ka = _smax_mva_to_imax_ka(smax_mva, line_vn_kv)
        line_idx = _create_line_pu(
            net,
            from_bus=fbus_pp,
            to_bus=tbus_pp,
            r_pu=float(spec["r_pu"]),
            x_pu=float(spec["x_pu"]),
            b_pu=float(spec.get("b_pu", 0.0)),
            sn_mva=MATPOWER_BASE_MVA,
            vn_kv=line_vn_kv,
            max_i_ka=max_i_ka,
            name=f"AggressiveMesh {fbus_mp}-{tbus_mp}",
        )
        net.line.at[line_idx, "max_loading_percent"] = float(line_max_loading_percent)
        branch_rows.append({
            "branch_id": extra_start_id + kk,
            "from_bus_mp": fbus_mp,
            "to_bus_mp": tbus_mp,
            "from_bus_pp": _mp_to_pp(fbus_mp),
            "to_bus_pp": _mp_to_pp(tbus_mp),
            "r_pu": float(spec["r_pu"]),
            "x_pu": float(spec["x_pu"]),
            "aggressive_stress_applied": True,
            "aggressive_r_scale": np.nan,
            "aggressive_x_scale": np.nan,
            "aggressive_smax_scale": np.nan,
            "b_pu": float(spec.get("b_pu", 0.0)),
            "rateA_raw": 0.0,
            "rateB_raw": 0.0,
            "rateC_raw": 0.0,
            "ratio_raw": 0.0,
            "angle_deg": 0.0,
            "status": 1,
            "angmin": -360.0,
            "angmax": 360.0,
            "from_kv": float(from_kv),
            "to_kv": float(to_kv),
            "is_transformer_like": False,
            "synthetic_smax_mva": float(smax_mva),
            "element_type": "line",
            "element_index": int(line_idx),
            "is_candidate_oltc": False,
        })
        extra_line_rows.append({
            "branch_id": extra_start_id + kk,
            "from_mp": fbus_mp,
            "to_mp": tbus_mp,
            "r_pu": float(spec["r_pu"]),
            "x_pu": float(spec["x_pu"]),
            "b_pu": float(spec.get("b_pu", 0.0)),
            "smax_mva": float(smax_mva),
            "line_idx": int(line_idx),
        })

    # --------------------------------------------------------
    # Metadata tables
    # --------------------------------------------------------
    net["bus_lookup_table"] = pd.DataFrame(
        {
            "bus_pp": list(range(len(BUS_DATA))),
            "bus_mp": BUS_ID_ORDER,
            "name": [f"Bus {bus_id}" for bus_id in BUS_ID_ORDER],
            "type": [int(r[1]) for r in BUS_DATA],
            "base_kv": [float(r[9]) for r in BUS_DATA],
        }
    )

    net["fixed_bus_shunt_table"] = pd.DataFrame(fixed_bus_shunt_rows)
    net["aggressive_direct_load_table"] = pd.DataFrame(aggressive_direct_rows)
    net["aggressive_extra_mesh_lines"] = pd.DataFrame(extra_line_rows)

    net["fixed_oltc_edges_ordered"] = list(FIXED_OLTC_EDGES_ORDERED)
    net["fixed_oltc_table"] = pd.DataFrame(
        [
            {
                "from_bus_pp": i,
                "to_bus_pp": j,
                "from_bus_mp": _pp_to_mp(i),
                "to_bus_mp": _pp_to_mp(j),
                "tap_min": FIXED_OLTC_CONFIGS_UNDIR[tuple(sorted((i, j)))].tap_min,
                "tap_max": FIXED_OLTC_CONFIGS_UNDIR[tuple(sorted((i, j)))].tap_max,
                "dV_percent": FIXED_OLTC_CONFIGS_UNDIR[tuple(sorted((i, j)))].dV_percent,
                "recommended_tap": RECOMMENDED_NONEXACT_OLTC_TAPS.get((i, j), RECOMMENDED_NONEXACT_OLTC_TAPS.get((j, i), 0)),
            }
            for (i, j) in FIXED_OLTC_EDGES_ORDERED
        ]
    )

    net["fixed_shunt_buses"] = list(FIXED_SHUNT_BUSES)
    net["fixed_shunt_table"] = pd.DataFrame(
        [
            {
                "bus_pp": b,
                "bus_mp": _pp_to_mp(b),
                "bcap_pu": float(FIXED_SHUNT_BCAP_PU[b]) * float(AGGRESSIVE_SHUNT_BCAP_SCALE.get(b, 1.0)),
            }
            for b in FIXED_SHUNT_BUSES
        ]
    )

    net["recommended_nonexact_oltc_taps"] = pd.DataFrame(
        [
            {
                "from_bus_pp": i,
                "to_bus_pp": j,
                "from_bus_mp": _pp_to_mp(i),
                "to_bus_mp": _pp_to_mp(j),
                "tap": int(tap),
            }
            for (i, j), tap in RECOMMENDED_NONEXACT_OLTC_TAPS.items()
        ]
    )

    net["recommended_nonexact_shunt_status"] = pd.DataFrame(
        [
            {
                "bus_pp": b,
                "bus_mp": _pp_to_mp(b),
                "status": int(RECOMMENDED_NONEXACT_SHUNT_STATUS[b]),
            }
            for b in sorted(RECOMMENDED_NONEXACT_SHUNT_STATUS)
        ]
    )

    net["branch_params_pu_table"] = pd.DataFrame(branch_rows)

    # --------------------------------------------------------
    # Optional PF-based calibration to improve OPF feasibility
    # --------------------------------------------------------
    effective_pf_branch_headroom = float(pf_branch_headroom)
    effective_pf_branch_floor_mva = float(pf_branch_floor_mva)
    effective_pf_voltage_margin_pu = float(pf_voltage_margin_pu)

    if calibrate_branch_limits_from_pf:
        _apply_pf_based_branch_limits(
            net,
            headroom=effective_pf_branch_headroom,
            min_floor_mva=effective_pf_branch_floor_mva,
        )

