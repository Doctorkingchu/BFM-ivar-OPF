def _default_branch_smax_mva(from_kv: float, to_kv: float, is_transformer: bool) -> float:
    hv = max(float(from_kv), float(to_kv))
    lv = min(float(from_kv), float(to_kv))

    # Deliberately tighter synthetic ratings than the earlier feasibility-friendly
    # variant. Combined with the aggressive local branch stress below, this helps
    # expose congestion and non-exact mesh behavior on case300.
    if is_transformer:
        if hv >= 300.0 and lv >= 200.0:
            return 1800.0
        if hv >= 300.0 and lv >= 100.0:
            return 1300.0
        if hv >= 200.0 and lv >= 100.0:
            return 950.0
        if hv >= 100.0 and lv >= 60.0:
            return 450.0
        if hv >= 50.0 and lv >= 10.0:
            return 220.0
        return 80.0

    if hv >= 300.0:
        return 1600.0
    if hv >= 200.0:
        return 1200.0
    if hv >= 100.0:
        return 650.0
    if hv >= 50.0:
        return 220.0
    if hv >= 10.0:
        return 80.0
    return 30.0


