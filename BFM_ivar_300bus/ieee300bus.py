def _runpp_calibration(net) -> bool:
    """Best-effort PF for limit/bound calibration."""
    attempts = [
        dict(algorithm="nr", init="flat", calculate_voltage_angles=True, enforce_q_lims=False, numba=False),
        dict(algorithm="nr", init="auto", calculate_voltage_angles=True, enforce_q_lims=False, numba=False),
        dict(algorithm="bfsw", init="flat", calculate_voltage_angles=False, enforce_q_lims=False, numba=False),
    ]
    for kw in attempts:
        try:
            pp.runpp(net, **kw)
            return True
        except Exception:
            continue
    return False


def _apply_pf_based_branch_limits(
    net,
    headroom: float = 1.35,
    min_floor_mva: float = 20.0,
):
    """
    Recalibrate synthetic branch ratings from an observed PF solution.

    For each line/trafo branch, define
        S_max,new = max(S_max,old, headroom * S_obs, min_floor_mva)
    where S_obs is the larger sending/receiving-end apparent power from PF.
    """
    if "branch_params_pu_table" not in net or net["branch_params_pu_table"].empty:
        return
    if not _runpp_calibration(net):
        return

    brdf = net["branch_params_pu_table"].copy()
    updated_rows = []

    for ridx, row in brdf.iterrows():
        et = str(row["element_type"])
        eidx = int(row["element_index"])
        sold = float(row["synthetic_smax_mva"])
        sobs = 0.0

        try:
            if et == "line" and hasattr(net, "res_line") and eidx in net.res_line.index:
                p1 = float(net.res_line.at[eidx, "p_from_mw"])
                q1 = float(net.res_line.at[eidx, "q_from_mvar"])
                p2 = float(net.res_line.at[eidx, "p_to_mw"])
                q2 = float(net.res_line.at[eidx, "q_to_mvar"])
                sobs = max(math.hypot(p1, q1), math.hypot(p2, q2))
            elif et == "trafo" and hasattr(net, "res_trafo") and eidx in net.res_trafo.index:
                ph = float(net.res_trafo.at[eidx, "p_hv_mw"])
                qh = float(net.res_trafo.at[eidx, "q_hv_mvar"])
                pl = float(net.res_trafo.at[eidx, "p_lv_mw"])
                ql = float(net.res_trafo.at[eidx, "q_lv_mvar"])
                sobs = max(math.hypot(ph, qh), math.hypot(pl, ql))
        except Exception:
            sobs = 0.0

        snew = max(sold, float(min_floor_mva), float(headroom) * float(sobs))
        brdf.at[ridx, "synthetic_smax_mva"] = snew

        if et == "line":
            try:
                vn_kv = float(row["from_kv"])
                net.line.at[eidx, "max_i_ka"] = _smax_mva_to_imax_ka(snew, vn_kv)
            except Exception:
                pass
        elif et == "trafo":
            try:
                net.trafo.at[eidx, "sn_mva"] = snew
            except Exception:
                pass

        updated_rows.append({
            "branch_id": int(row["branch_id"]),
            "element_type": et,
            "element_index": eidx,
            "from_bus_mp": int(row["from_bus_mp"]),
            "to_bus_mp": int(row["to_bus_mp"]),
            "smax_old_mva": sold,
            "s_obs_pf_mva": sobs,
            "smax_new_mva": snew,
        })

    net["branch_params_pu_table"] = brdf
    net["pf_calibrated_branch_limits"] = pd.DataFrame(updated_rows)


def _widen_voltage_bounds_from_pf(
    net,
    margin_pu: float = 0.01,
):
    """
    Expand bus voltage bounds just enough to contain an observed PF solution.
    This is optional and intended only to avoid immediate infeasibility from
    overly tight raw MATPOWER bounds during warm-started OPF experiments.
    """
    if not _runpp_calibration(net):
        return
    if not hasattr(net, "res_bus") or net.res_bus is None or net.res_bus.empty:
        return

    rows = []
    for i in net.bus.index:
        vm = float(net.res_bus.at[i, "vm_pu"])
        vmin_old = float(net.bus.at[i, "min_vm_pu"])
        vmax_old = float(net.bus.at[i, "max_vm_pu"])
        vmin_new = min(vmin_old, vm - float(margin_pu))
        vmax_new = max(vmax_old, vm + float(margin_pu))
        net.bus.at[i, "min_vm_pu"] = vmin_new
        net.bus.at[i, "max_vm_pu"] = vmax_new
        rows.append({
            "bus_pp": int(i),
            "bus_mp": int(net.bus.at[i, "mpc_bus_id"]) if "mpc_bus_id" in net.bus.columns else int(i),
            "vm_pf": vm,
            "min_old": vmin_old,
            "max_old": vmax_old,
            "min_new": vmin_new,
            "max_new": vmax_new,
        })
    net["pf_widened_voltage_bounds"] = pd.DataFrame(rows)


